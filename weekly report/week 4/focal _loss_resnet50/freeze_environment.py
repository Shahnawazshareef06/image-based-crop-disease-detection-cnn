"""Record the exact software environment used for a TerraVista run.

Run (in the same environment you train in, e.g. the Kaggle GPU session):
    python freeze_environment.py

Writes, next to this script:
    requirements-lock.txt   pinned versions of the packages this project imports
    environment_report.json Python, OS, PyTorch/TorchVision/CUDA and GPU details

Commit both files together with your results so another person can rebuild the
same environment. The pinned file reflects the machine you ran this on.
"""
from __future__ import annotations

import json
import platform
import sys
from importlib import metadata
from pathlib import Path

# Each entry lists acceptable distribution names (first one found is pinned).
PACKAGES = [
    ("numpy",),
    ("opencv-python-headless", "opencv-python"),
    ("scikit-learn",),
    ("pandas",),
    ("Pillow",),
    ("torch",),
    ("torchvision",),
]


def _find(names):
    for name in names:
        try:
            return name, metadata.version(name)
        except metadata.PackageNotFoundError:
            continue
    return names[0], None


def main() -> None:
    base = Path(__file__).resolve().parent
    pins, missing, versions = [], [], {}
    for names in PACKAGES:
        name, version = _find(names)
        if version is None:
            missing.append(name)
        else:
            pins.append(f"{name}=={version}")
            versions[name] = version

    lines = [
        "# Generated by freeze_environment.py - do not edit by hand.",
        "# torch/torchvision are normally preinstalled CUDA builds; do not blindly reinstall them.",
        *pins,
    ]
    if missing:
        lines.append("# NOT INSTALLED when this file was generated: " + ", ".join(missing))
    (base / "requirements-lock.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    report = {
        "python": sys.version.replace("\n", " "),
        "platform": platform.platform(),
        "packages": versions,
        "missing_packages": missing,
        "torch": None,
    }
    try:
        from terravista_bootstrap import apply_kaggle_triton_guard

        apply_kaggle_triton_guard()  # same Triton workaround the experiments use
        import torch

        report["torch"] = {
            "version": torch.__version__,
            "cuda_build": torch.version.cuda,
            "cuda_available": bool(torch.cuda.is_available()),
            "cudnn_version": torch.backends.cudnn.version(),
            "gpu_names": [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())],
        }
    except Exception as exc:  # report, do not fail: the lock file is still useful
        report["torch"] = f"not importable: {type(exc).__name__}: {exc}"
    (base / "environment_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print("Wrote requirements-lock.txt and environment_report.json")
    if missing:
        print("Warning - not installed:", ", ".join(missing))


if __name__ == "__main__":
    main()
